	/* set DQ odt/ocd sel */
	REG32_MASK(DDR_PHY_DQ_ODT_SEL0, DQ_ODT_SEL_VALUE, DQ_ODT_SEL_MASK);
	REG32_MASK(DDR_PHY_DQ_OCD_SEL0, DQ_OCD_SEL_VALUE, DQ_OCD_SEL_MASK);

