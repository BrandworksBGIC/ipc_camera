	REG32_MASK(DDR_PHY_CKE_OCD_SEL, CKE_OCD_SEL_VALUE, CKE_OCD_SEL_MASK);
	REG32_MASK(DDR_PHY_ADR_OCD_SEL, ADR_OCD_SEL_VALUE, ADR_OCD_SEL_MASK);
