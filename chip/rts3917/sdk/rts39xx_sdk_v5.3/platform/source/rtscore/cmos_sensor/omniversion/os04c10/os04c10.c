static int os04c10_get_info(uint32_t isp_id,
			struct rts_isp_sensor_info *info)
{
	int i;
	struct rts_isp_snr_pwr *up = &info->power_up;
	struct rts_isp_snr_pwr *down = &info->power_down;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
		return -RTS_ISP_EINVAL;

	i = 0;
	info->modes.mode[i].hdr = RTS_ISP_HDR_NONE;
	info->modes.mode[i].size.w = 2688;
	info->modes.mode[i].size.h = 1520;
	info->modes.mode[i].fps = 30;
	i++;
	info->modes.mode[i].hdr = RTS_ISP_HDR_LINE_2TO1;
	info->modes.mode[i].size.w = 2688;
	info->modes.mode[i].size.h = 1520;
	info->modes.mode[i].fps = 30;
	i++;
	info->modes.num = i;

	info->i2c.i2c_id = 0x36;
	info->i2c.addr_len = 2;
	info->i2c.data_len = 1;

	i = 0;
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_LOW, 1000);
	set_power_item(&up->items[i++], SNR_IO_POWER, PWR_1V8, 1000);
	set_power_item(&up->items[i++], SNR_ANALOG_POWER, PWR_2V8, 1000);
	set_power_item(&up->items[i++], SNR_CORE_POWER, PWR_1V2, 5000);
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_HIGH, 5000);
	set_power_item(&up->items[i++], SNR_HCLK, CLK_24M, 20000);
	up->num = i;
	i = 0;
	set_power_item(&down->items[i++], SNR_HCLK, 0, 1000);
	set_power_item(&down->items[i++], SNR_RST_GPIO, 0, 0);
	set_power_item(&down->items[i++], SNR_CORE_POWER, 0, 0);
	set_power_item(&down->items[i++], SNR_ANALOG_POWER, 0, 0);
	set_power_item(&down->items[i++], SNR_IO_POWER, 0, 0);
	set_power_item(&down->items[i++], SNR_PWDN_GPIO, 0, 0);
	down->num = i;

	return RTS_ISP_OK;
}

static int os04c10_get_init_info(uint32_t isp_id,
				 const struct rts_isp_sensor_mode *mode,
			       struct rts_isp_sensor_init_info *info)
{
	struct os04c10_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
		return -RTS_ISP_EINVAL;

	debug("os04c10 get fps %.1f init info\n", mode->fps);

	status = &g_status[isp_id];
	status->hdr = mode->hdr;

	if (mode->hdr == RTS_ISP_HDR_NONE) {
		set_init_i2c_regs(info->sensor_regs[0],
					g_os04c10_i2c_linear_regs, 0);

		info->interface.interface = SNR_INTERFACE_MIPI;
		info->interface.mipi.hdr = MIPI_HDR_NONE;
		info->interface.mipi.lanes = MIPI_LANE0 | MIPI_LANE1;
		info->interface.mipi.hs_term = 0x05;
		info->interface.type = RAW_SENSOR;
		info->interface.bit_depth = SNR_10BIT;

		info->size.w = 2696;
		info->size.h = 1528;
		info->start.x = 0;
		info->start.y = 0;

		info->hts = 3117;
		info->pclk = 147200000;
		info->min_vts = 1574;
		info->max_vts = 65535;
		status->exp_step = 1e6 * info->hts / info->pclk;
	} else {
		set_init_i2c_regs(info->sensor_regs[0],
					g_os04c10_i2c_hdr_regs, 0);
		info->interface.interface = SNR_INTERFACE_MIPI;
		info->interface.mipi.hdr = MIPI_HDR_VC;
		info->interface.mipi.lanes = MIPI_LANE0 | MIPI_LANE1;
		info->interface.mipi.hs_term = 0x07;
		info->interface.type = RAW_SENSOR;
		info->interface.bit_depth = SNR_10BIT;
		info->interface.type_config.raw.bayer = SNR_BGGR;

		info->size.w = 2688;
		info->size.h = 1520;
		info->start.x = 0;
		info->start.y = 0;

		info->hts = 5782;
		info->pclk = 272000000;
		info->min_vts = 1568;
		info->max_vts = info->min_vts * 2;
		status->exp_step = 1e6 * info->hts / 2 / info->pclk;
		info->exposure_step = status->exp_step;
	}
	return RTS_ISP_OK;
}

static int os04c10_start(uint32_t isp_id)
{
	struct os04c10_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];
	status->last_exposure = 0;

	return RTS_ISP_OK;
}

static int os04c10_get_exposure_range(uint32_t isp_id, uint32_t vts,
				     float ratio[RTS_ISP_HDR_CHAN_MAX - 1],
				     float min_exposure[RTS_ISP_HDR_CHAN_MAX],
				     float max_exposure[RTS_ISP_HDR_CHAN_MAX])
{
	struct os04c10_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];
	if (status->hdr == RTS_ISP_HDR_NONE) {
		min_exposure[0] = 2 * status->exp_step;
		max_exposure[0] = (vts - 8) * status->exp_step;
	} else {
		uint32_t tmp1;
		uint32_t tmp2;

		tmp1 = (uint32_t)((vts - 12)/(ratio[0] + 1));
		tmp2 = (uint32_t)((vts - 8) / ratio[0]);

		tmp1 = tmp1 < tmp2 ? tmp1 : tmp2;
		max_exposure[1] = tmp1 * status->exp_step;
		min_exposure[1] = 12 * status->exp_step;
		max_exposure[0] = max_exposure[1] * ratio[0];
		min_exposure[0] = min_exposure[1] * ratio[0];
	}
	return RTS_ISP_OK;
}

static uint16_t get_sensor_gain_reg(float fgain)
{
	uint16_t reg;

	fgain = fgain > 15.5f ? 15.5f : fgain;
	reg = ((int)fgain << 7) | (int)((fgain - (int)fgain) * 128.0f);

	return reg;
}

static float get_sensor_real_gain(uint16_t reg_value)
{
	float fgain;

	fgain = (float)(reg_value >> 7) + (reg_value & 0x7f) / 128.0f;

	return fgain;
}

static int os04c10_get_tuned_again(uint32_t isp_id,
				   float again[RTS_ISP_HDR_CHAN_MAX])
{
	int gain_reg;

	if (isp_id >= SUPPORTED_ISP_NUM || !again)
		return -RTS_ISP_EINVAL;

	gain_reg = get_sensor_gain_reg(again[0]);
	again[0] = get_sensor_real_gain(gain_reg);
	gain_reg = get_sensor_gain_reg(again[1]);
	again[1] = get_sensor_real_gain(gain_reg);

	return RTS_ISP_OK;
}

static int os04c10_get_tuned_dgain(uint32_t isp_id,
				   float dgain[RTS_ISP_HDR_CHAN_MAX])
{
	if (isp_id >= SUPPORTED_ISP_NUM || !dgain)
		return -RTS_ISP_EINVAL;

	dgain[0] = 1.0f;
	dgain[1] = 1.0f;

	return RTS_ISP_OK;
}

static uint32_t clip_d_word(uint32_t current, uint32_t minimum,
			    uint32_t maximum)
{
	if (current > maximum)
		return maximum;
	if (current < minimum)
		return minimum;
	return current;
}

static int os04c10_get_exposure_gain_info(uint32_t isp_id,
		const struct rts_isp_sensor_exp_gain *exp_gain,
		struct rts_isp_sync_regs *regs)
{
	int i;
	struct os04c10_status *status;
	struct rts_isp_sync_reg *reg;

	if (isp_id >= SUPPORTED_ISP_NUM || !exp_gain || !regs)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];

	if (status->hdr == RTS_ISP_HDR_NONE) { /* LINEAR MODE */
		uint16_t gain_reg;
		uint32_t vts;
		uint32_t exposure_reg;
		uint32_t exp_reg_value;

		vts = exp_gain->vts;
		gain_reg = get_sensor_gain_reg(exp_gain->analog_gain[0] *
				exp_gain->digital_gain[0]);

		reg = regs->reg;
		exposure_reg = exp_gain->exposure[0] / status->exp_step + 0.5f;
		exp_reg_value = clip_d_word(exposure_reg, 2, exp_gain->vts - 8);
		i = 0;
		if (abs(status->last_exposure -
			exp_gain->exposure[0]) > 0.001f) {
			/* group */
			set_sync_i2c(&reg[i++], 0x3208, 0x01);

			/* exposure */
			set_sync_i2c(&reg[i++], 0x3501, exp_reg_value  >> 8);
			set_sync_i2c(&reg[i++], 0x3502, exp_reg_value & 0xff);
			status->last_exposure = exp_gain->exposure[0];
			/* gain */
			set_sync_i2c(&reg[i++], 0x3508, gain_reg >> 8);
			set_sync_i2c(&reg[i++], 0x3509, gain_reg & 0xff);
			/* dummy */
			set_sync_i2c(&reg[i++], 0x380e, vts >> 8);
			set_sync_i2c(&reg[i++], 0x380f, vts & 0xff);

			/* end group */
			set_sync_i2c(&reg[i++], 0x3208, 0x11);
			set_sync_i2c(&reg[i++], 0x3208, 0xe1);
		} else {
			/* group */
			set_sync_i2c(&reg[i++], 0x3208, 0x00);

			/* gain */
			set_sync_i2c(&reg[i++], 0x3508, gain_reg >> 8);
			set_sync_i2c(&reg[i++], 0x3509, gain_reg & 0xff);
			/* dummy */
			set_sync_i2c(&reg[i++], 0x380e, vts >> 8);
			set_sync_i2c(&reg[i++], 0x380f, vts & 0xff);

			/* end group */
			set_sync_i2c(&reg[i++], 0x3208, 0x10);
			set_sync_i2c(&reg[i++], 0x3208, 0xe0);
		}
		regs->num = i;
	} else { /* HDR MODE */
		uint16_t exp_cnt[2];
		uint16_t gain_regs[2];

		for (i = 0; i < 2; i++) {
			exp_cnt[i] = exp_gain->exposure[i] / status->exp_step;
			gain_regs[i] =
			get_sensor_gain_reg(exp_gain->analog_gain[i]
			 * exp_gain->digital_gain[i]);
			exp_cnt[i] = clip_d_word(exp_cnt[i], 2, exp_cnt[i]);
		}
		reg = regs->reg;
		i = 0;

		/* group */
		set_sync_i2c(&reg[i++], 0x3208, 0x00);

		/* set long exposure */
		set_sync_i2c(&reg[i++], 0x3501, exp_cnt[0] >> 8);
		set_sync_i2c(&reg[i++], 0x3502, exp_cnt[0] & 0xff);
		/* set short exposure */
		set_sync_i2c(&reg[i++], 0x3511, exp_cnt[1] >> 8);
		set_sync_i2c(&reg[i++], 0x3512, exp_cnt[1] & 0xff);

		/* set long gain */
		set_sync_i2c(&reg[i++], 0x3508, (gain_regs[0] >> 8));
		set_sync_i2c(&reg[i++], 0x3509, (gain_regs[0] & 0xff));
		/* set short gain */
		set_sync_i2c(&reg[i++], 0x350c, (gain_regs[1] >> 8));
		set_sync_i2c(&reg[i++], 0x350d, (gain_regs[1] & 0xff));

		/* end group */
		set_sync_i2c(&reg[i++], 0x3208, 0x10);
		set_sync_i2c(&reg[i++], 0x3208, 0xe0);

		set_sync_info(&reg[i++], 1, RTS_ISP_INT_DATA_START);

		/* group */
		set_sync_i2c(&reg[i++], 0x3208, 0x01);

		/* vts */
		set_sync_i2c(&reg[i++], 0x380e, (exp_gain->vts) >> 8);
		set_sync_i2c(&reg[i++], 0x380f, (exp_gain->vts) & 0xff);

		/* end group */
		set_sync_i2c(&reg[i++], 0x3208, 0x11);
		set_sync_i2c(&reg[i++], 0x3208, 0xe1);

		regs->num = i;
	}
	return RTS_ISP_OK;
}

static int os04c10_get_mirror_flip(uint32_t isp_id,
				  const struct rts_isp_mirror_flip *mf_info,
				  struct rts_isp_sync_regs *regs)
{
	int i = 0;
	uint32_t val1 = 0x08;
	uint32_t val2 = 0x24;
	struct rts_isp_sync_reg *reg;

	if (isp_id >= SUPPORTED_ISP_NUM || !mf_info || !regs)
		return -RTS_ISP_EINVAL;

	rts_isp_drop_frames(isp_id, 1);
	if (mf_info->mirror) {
		val1 = 0;
		val2 = 0x24;
	} else if (mf_info->flip) {
		val1 |= 0x30;
		val2 = 0x04;
	}
	reg = regs->reg;
	set_sync_i2c_mask(&reg[i++], 0x3820, 0x80 | val1, 0xb8);
	set_sync_i2c_mask(&reg[i++], 0x3716, val2, 0x20);

	regs->num = i;
	return RTS_ISP_OK;
}

static int os04c10_check(uint32_t isp_id)
{
	int ret;
	int id;
	struct rts_isp_i2c_reg reg = {};

	reg.addr = 0x300b;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);
	if (ret)
		return ret;
	id = reg.data << 8;

	reg.addr = 0x300c;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);
	if (ret)
		return ret;
	id |= reg.data;

	if (id == 0x0443)
		return RTS_ISP_OK;
	else
		return -RTS_ISP_EINVAL;
}

