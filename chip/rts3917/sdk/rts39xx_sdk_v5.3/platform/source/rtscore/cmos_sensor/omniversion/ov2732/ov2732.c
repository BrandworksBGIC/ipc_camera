static int ov2732_get_info(uint32_t isp_id, struct rts_isp_sensor_info *info)
{
	int i;
	struct rts_isp_snr_pwr *up = &info->power_up;
	struct rts_isp_snr_pwr *down = &info->power_down;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
		return -RTS_ISP_EINVAL;

	i = 0;
	info->modes.mode[i].hdr = RTS_ISP_HDR_NONE;
	info->modes.mode[i].size.w = 1920;
	info->modes.mode[i].size.h = 1080;
	info->modes.mode[i].fps = 30;
	i++;
	info->modes.mode[i].hdr = RTS_ISP_HDR_NONE;
	info->modes.mode[i].size.w = 1920;
	info->modes.mode[i].size.h = 1080;
	info->modes.mode[i].fps = 60;
	i++;
	info->modes.mode[i].hdr = RTS_ISP_HDR_NONE;
	info->modes.mode[i].size.w = 320;
	info->modes.mode[i].size.h = 240;
	info->modes.mode[i].fps = 120;
	i++;
	info->modes.mode[i].hdr = RTS_ISP_HDR_LINE_2TO1;
	info->modes.mode[i].size.w = 1920;
	info->modes.mode[i].size.h = 1080;
	info->modes.mode[i].fps = 30;
	i++;
	info->modes.num = i;

	info->i2c.i2c_id = 0x36;
	info->i2c.addr_len = 2;
	info->i2c.data_len = 1;

	i = 0;
	set_power_item(&up->items[i++], SNR_PWDN_GPIO, GPIO_HIGH, 0);
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_LOW, 2000);
	set_power_item(&up->items[i++], SNR_IO_POWER, PWR_1V8, 0);
	set_power_item(&up->items[i++], SNR_ANALOG_POWER, PWR_2V8, 0);
	set_power_item(&up->items[i++], SNR_CORE_POWER, PWR_1V2, 11000);
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_HIGH, 2000);
	set_power_item(&up->items[i++], SNR_HCLK, CLK_24M, 5000);
	up->num = i;
	i = 0;
	set_power_item(&down->items[i++], SNR_RST_GPIO, GPIO_LOW, 0);
	set_power_item(&down->items[i++], SNR_PWDN_GPIO, GPIO_LOW, 0);
	set_power_item(&down->items[i++], SNR_IO_POWER, PWR_NONE, 0);
	set_power_item(&down->items[i++], SNR_CORE_POWER, PWR_NONE, 0);
	set_power_item(&down->items[i++], SNR_ANALOG_POWER, PWR_NONE, 0);
	set_power_item(&down->items[i++], SNR_HCLK, CLK_NONE, 0);
	down->num = i;

	return RTS_ISP_OK;
}


static int ov2732_get_init_info(uint32_t isp_id,
				const struct rts_isp_sensor_mode *mode,
				struct rts_isp_sensor_init_info *info)
{
	struct ov2732_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
		return -RTS_ISP_EINVAL;

	debug("ov2732 get fps %.1f init info\n", mode->fps);

	status = &g_status[isp_id];
	status->hdr = mode->hdr;

	if (mode->hdr == RTS_ISP_HDR_LINE_2TO1) {
		//hdr vc mode
		set_init_i2c_regs(info->sensor_regs[0],
			g_ov2732_init_regs_stagger_hdr_setting1, 0);
		set_init_i2c_regs(info->sensor_regs[1],
			g_ov2732_init_regs_stagger_hdr_setting2, 0);

		info->interface.mipi.hdr = MIPI_HDR_VC;
		info->interface.interface = SNR_INTERFACE_MIPI;
		info->interface.mipi.lanes = MIPI_LANE0 | MIPI_LANE1;
		info->interface.mipi.hs_term = 0x4;
		info->interface.type = RAW_SENSOR;
		info->interface.bit_depth = SNR_10BIT;

		info->size.w = 1920;
		info->size.h = 1080;
		info->start.x = 0;
		info->start.y = 0;

		info->hts = 5067;
		info->pclk = 180000000;
		info->min_vts = status->min_vts = 1184;
		info->max_vts = 1184;

		status->exp_step = 1e6 * info->hts / 2 / info->pclk; /* us */
	} else {
		if (mode->fps == 120) {
			set_init_i2c_regs(info->sensor_regs[0],
				g_ov2732_init_linear_120fps_setting, 0);

			info->interface.interface = SNR_INTERFACE_MIPI;
			info->interface.mipi.hdr = MIPI_HDR_NONE;
			info->interface.mipi.lanes = MIPI_LANE0 | MIPI_LANE1;
			info->interface.mipi.hs_term = 0x4;
			info->interface.type = RAW_SENSOR;
			info->interface.bit_depth = SNR_10BIT;

			info->size.w = 320;
			info->size.h = 240;
			info->start.x = 0;
			info->start.y = 0;

			info->hts = 2027;
			info->pclk = 144000000;
			info->min_vts = status->min_vts = 592;
			info->max_vts = 65535;

			status->exp_step = 1e6 * info->hts / info->pclk;
		} else if (mode->fps == 60) {
			set_init_i2c_regs(info->sensor_regs[0],
				  g_ov2732_init_linear_60fps_setting, 0);

			info->interface.interface = SNR_INTERFACE_MIPI;
			info->interface.mipi.hdr = MIPI_HDR_NONE;
			info->interface.mipi.lanes = MIPI_LANE0 | MIPI_LANE1;
			info->interface.mipi.hs_term = 0x4;
			info->interface.type = RAW_SENSOR;
			info->interface.bit_depth = SNR_10BIT;

			info->size.w = 1920;
			info->size.h = 1080;
			info->start.x = 0;
			info->start.y = 0;

			info->hts = 2027;
			info->pclk = 144000000;
			info->min_vts = status->min_vts = 1184;
			info->max_vts = 65535;

			status->exp_step = 1e6 * info->hts / info->pclk;
		} else if (mode->fps == 30) {
			set_init_i2c_regs(info->sensor_regs[0],
				  g_ov2732_init_linear_30fps_setting, 0);

			info->interface.interface = SNR_INTERFACE_MIPI;
			info->interface.mipi.hdr = MIPI_HDR_NONE;
			info->interface.mipi.lanes = MIPI_LANE0 | MIPI_LANE1;
			info->interface.mipi.hs_term = 0x4;
			info->interface.type = RAW_SENSOR;
			info->interface.bit_depth = SNR_10BIT;

			info->size.w = 1920;
			info->size.h = 1080;
			info->start.x = 0;
			info->start.y = 0;

			info->hts = 4054;
			info->pclk = 144000000;
			info->min_vts = status->min_vts = 1184;
			info->max_vts = 65535;

			status->exp_step = 1e6 * info->hts / info->pclk;
		}
	}

	return RTS_ISP_OK;
}

static int ov2732_start(uint32_t isp_id)
{
	struct ov2732_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];

	status->last_exposure = 0;

	return RTS_ISP_OK;
}

static uint32_t clip_d_word(uint32_t current, uint32_t minimum,
			    uint32_t maximum)
{
	if (current > maximum)
		return maximum;
	if (current < minimum)
		return minimum;
	return current;
}

static int ov2732_get_exposure_range(uint32_t isp_id, uint32_t vts,
				     float ratio[RTS_ISP_HDR_CHAN_MAX - 1],
				     float min_exposure[RTS_ISP_HDR_CHAN_MAX],
				     float max_exposure[RTS_ISP_HDR_CHAN_MAX])
{
	struct ov2732_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM)
		return -RTS_ISP_EINVAL;
	status = &g_status[isp_id];
	if (status->hdr == RTS_ISP_HDR_NONE) {
		min_exposure[0] = status->exp_step;
		max_exposure[0] = (vts - 8) * status->exp_step;
	} else {
		uint32_t tmp;

		tmp = (uint32_t)((vts - 8) / (ratio[0] + 1));
		max_exposure[1] = tmp * status->exp_step;
		min_exposure[1] = 12 * status->exp_step;
		max_exposure[0] = max_exposure[1] * ratio[0];
		min_exposure[0] = min_exposure[1] * ratio[0];
	}

	return RTS_ISP_OK;
}

static uint16_t get_sensor_gain_reg(float fgain)
{
	uint16_t reg_value = 0;

	reg_value = (uint16_t)(fgain * 128.0);
	reg_value = clip_d_word(reg_value, 128, 128 * 14.0);

	return reg_value;
}

static float get_sensor_real_gain(uint16_t reg_value)
{
	return (float)reg_value / 128;
}

static int ov2732_get_tuned_again(uint32_t isp_id, float *again)
{
	int gain_reg;

	if (isp_id >= SUPPORTED_ISP_NUM || !again)
		return -RTS_ISP_EINVAL;

	gain_reg = get_sensor_gain_reg(again[0]);
	again[0] = get_sensor_real_gain(gain_reg);
	gain_reg = get_sensor_gain_reg(again[1]);
	again[1] = get_sensor_real_gain(gain_reg);

	return RTS_ISP_OK;
}

static int ov2732_get_tuned_dgain(uint32_t isp_id,
				  float dgain[RTS_ISP_HDR_CHAN_MAX])
{
	if (isp_id >= SUPPORTED_ISP_NUM || !dgain)
		return -RTS_ISP_EINVAL;

	dgain[0] = 1.0f;
	dgain[1] = 1.0f;

	return RTS_ISP_OK;
}

static int ov2732_get_exposure_gain_info(uint32_t isp_id,
		const struct rts_isp_sensor_exp_gain *exp_gain,
		struct rts_isp_sync_regs *regs)
{
	int i;
	struct ov2732_status *status;
	struct rts_isp_sync_reg *reg;

	if (isp_id >= SUPPORTED_ISP_NUM || !exp_gain || !regs)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];

	if (status->hdr == RTS_ISP_HDR_NONE) {
		uint32_t exposure_rows;
		uint16_t gain;

		exposure_rows = exp_gain->exposure[0] / status->exp_step;
		gain = get_sensor_gain_reg(exp_gain->analog_gain[0] *
					exp_gain->digital_gain[0]);
		reg = regs->reg;
		i = 0;
		// set vts
		set_sync_i2c(&reg[i++], 0x380e, exp_gain->vts >> 8);
		set_sync_i2c(&reg[i++], 0x380f, exp_gain->vts & 0xff);
		// set exposure
		set_sync_i2c(&reg[i++], 0x3502, (exposure_rows << 4) & 0xff);
		set_sync_i2c(&reg[i++], 0x3501, (exposure_rows << 4) >> 8);
		set_sync_i2c(&reg[i++], 0x3500, (exposure_rows << 4) >> 16);
		// set gain
		set_sync_i2c(&reg[i++], 0x3508, gain >> 8);
		set_sync_i2c(&reg[i++], 0x3509, gain & 0xff);
		regs->num = i;
	} else {
		uint32_t exp_cnt[2];
		uint16_t gain_reg[2];

		for (i = 0; i < 2; i++) {
			exp_cnt[i] = exp_gain->exposure[i] / status->exp_step;
			gain_reg[i] =
				get_sensor_gain_reg(exp_gain->analog_gain[i] *
					exp_gain->digital_gain[i]);
		}
		reg = regs->reg;

		i = 0;
		set_sync_i2c(&reg[i++], 0x3208, 0x00);
		/* set long exposure */
		set_sync_i2c(&reg[i++], 0x3500, (exp_cnt[0] << 4) >> 16);
		set_sync_i2c(&reg[i++], 0x3501, (exp_cnt[0] << 4) >> 8);
		set_sync_i2c(&reg[i++], 0x3502, (exp_cnt[0] << 4) & 0xff);
		/* set short exposure */
		set_sync_i2c(&reg[i++], 0x3510, (exp_cnt[1] << 4) >> 16);
		set_sync_i2c(&reg[i++], 0x3511, (exp_cnt[1] << 4) >> 8);
		set_sync_i2c(&reg[i++], 0x3512, (exp_cnt[1] << 4) & 0xff);
		/* set long gain */
		set_sync_i2c(&reg[i++], 0x3508, (gain_reg[0] >> 8));
		set_sync_i2c(&reg[i++], 0x3509, (gain_reg[0] & 0xff));
		/* set short gain */
		set_sync_i2c(&reg[i++], 0x350C, (gain_reg[1] >> 8));
		set_sync_i2c(&reg[i++], 0x350D, (gain_reg[1] & 0xff));

		set_sync_i2c(&reg[i++], 0x3208, 0x10);
		set_sync_i2c(&reg[i++], 0x320D, 0x00);
		set_sync_i2c(&reg[i++], 0x3208, 0xe0);
		regs->num = i;
	}
	return RTS_ISP_OK;
}

static int ov2732_get_mirror_flip(uint32_t isp_id,
				  const struct rts_isp_mirror_flip *mf_info,
				  struct rts_isp_sync_regs *regs)
{
	int i = 0;
	uint32_t val = 0x8;
	struct rts_isp_sync_reg *reg;

	if (isp_id >= SUPPORTED_ISP_NUM || !mf_info || !regs)
		return -RTS_ISP_EINVAL;

	rts_isp_drop_frames(isp_id, 1);
	if (mf_info->mirror)
		val = 0;
	if (mf_info->flip)
		val |= 0x10;
	reg = regs->reg;
	set_sync_i2c_mask(&reg[i++], 0x3820, 0x80 | val, 0x98);
	regs->num = i;

	return RTS_ISP_OK;
}

static int ov2732_check(uint32_t isp_id)
{
	int ret;
	int id;
	struct rts_isp_i2c_reg reg = {};

	reg.addr = 0x300a;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);
	if (ret)
		return ret;
	id = reg.data << 16;

	reg.addr = 0x300b;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);
	if (ret)
		return ret;
	id = reg.data << 8;

	reg.addr = 0x300c;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);
	if (ret)
		return ret;
	id |= reg.data;

	if (id == 0x002732)
		return RTS_ISP_OK;
	else
		return -RTS_ISP_EINVAL;
}

