static int imx634_get_info(uint32_t isp_id, struct rts_isp_sensor_info *info)
{
	int i;
	struct rts_isp_snr_pwr *up = &info->power_up;
	struct rts_isp_snr_pwr *down = &info->power_down;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
		return -RTS_ISP_EINVAL;

	info->modes.mode[0].hdr = RTS_ISP_HDR_NONE;
	info->modes.mode[0].size.w = 2560 - IMX634_DECREASE_WIDTH;
	info->modes.mode[0].size.h = 1920;
	info->modes.mode[0].fps = g_imx634_fps_info[0].fps;
	info->modes.num = 1;

	info->i2c.i2c_id = 0x10;
	info->i2c.addr_len = 2;
	info->i2c.data_len = 1;

	i = 0;
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_LOW, 0);
	set_power_item(&up->items[i++], SNR_ANALOG_POWER, PWR_2V8, 0);
	set_power_item(&up->items[i++], SNR_CORE_POWER, PWR_1V2, 0);
	set_power_item(&up->items[i++], SNR_IO_POWER, PWR_1V8, 1);
	set_power_item(&up->items[i++], SNR_HCLK, CLK_24M, 1);
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_HIGH, 5500);
	up->num = i;
	i = 0;
	set_power_item(&down->items[i++], SNR_RST_GPIO, 0, 1);
	set_power_item(&down->items[i++], SNR_HCLK, 0, 1);
	set_power_item(&down->items[i++], SNR_IO_POWER, 0, 0);
	set_power_item(&down->items[i++], SNR_CORE_POWER, 0, 0);
	set_power_item(&down->items[i++], SNR_ANALOG_POWER, 0, 0);
	down->num = i;

	return RTS_ISP_OK;
}

static const struct fps_info *imx634_get_fps_info(uint16_t fps)
{
	int i;

	for (i = 0; i < ARRAY_SIZE(g_imx634_fps_info); i++)
		if (fps == g_imx634_fps_info[i].fps)
			break;
	if (i == ARRAY_SIZE(g_imx634_fps_info))
		return NULL;

	return &g_imx634_fps_info[i];
}

static int imx634_get_init_info(uint32_t isp_id,
				const struct rts_isp_sensor_mode *mode,
			       struct rts_isp_sensor_init_info *info)
{
	const struct fps_info *fps_info;
	struct imx634_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
		return -RTS_ISP_EINVAL;

	debug("imx634 get fps %.1f init info\n", mode->fps);

	status = &g_status[isp_id];
	fps_info = imx634_get_fps_info(mode->fps);
	if (!fps_info)
		return -RTS_ISP_EINVAL;

	debug("fps: %u, pclk: %u, clk_div: %u, hts: %u\n",
	      fps_info->fps, fps_info->clk, fps_info->clk_div, fps_info->hts);

	set_init_i2c_regs(info->sensor_regs[0], g_imx634_i2c_init_regs, 0);

	info->interface.interface = SNR_INTERFACE_MIPI;
	info->interface.mipi.lanes = MIPI_LANE0 | MIPI_LANE1;
	info->interface.mipi.hs_term = 0x4;
	info->interface.type = RAW_SENSOR;
	info->interface.bit_depth = SNR_10BIT;

	info->size.w = 2564;
	info->size.h = 1920;
	info->start.x = 1 + IMX634_DECREASE_WIDTH / 2;
	info->start.y = 0;

	info->hts = fps_info->hts;
	info->pclk = fps_info->clk;
	info->min_vts = status->min_vts = 2125;
	info->max_vts = 65535 - info->min_vts;

	status->exp_step = 1e6 * info->hts / info->pclk; /* us */

	return RTS_ISP_OK;
}

static int imx634_start(uint32_t isp_id)
{
	struct imx634_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];

	status->last_exposure = 0;

	return RTS_ISP_OK;
}

static uint16_t get_sensor_gain_reg(float fgain)
{
	uint16_t reg_value = 0;

	if (fgain >= 16)
		reg_value = 0xF0;
	else
		reg_value = 256 - (uint16_t)(256 / (double)fgain);

	return reg_value;
}

static float get_sensor_real_gain(uint16_t reg_value)
{
	float gain;

	gain = (float)(256 / (double)(256 - reg_value));

	return gain;
}

static uint32_t clip_d_word(uint32_t current, uint32_t minimum,
			    uint32_t maximum)
{
	if (current > maximum)
		return maximum;
	if (current < minimum)
		return minimum;
	return current;
}

static int imx634_get_tuned_again(uint32_t isp_id,
				  float again[RTS_ISP_HDR_CHAN_MAX])
{
	int gain_reg;

	if (isp_id >= SUPPORTED_ISP_NUM || !again)
		return -RTS_ISP_EINVAL;

	gain_reg = get_sensor_gain_reg(again[0]);
	again[0] = get_sensor_real_gain(gain_reg);

	return RTS_ISP_OK;
}

static int imx634_get_tuned_dgain(uint32_t isp_id,
				  float dgain[RTS_ISP_HDR_CHAN_MAX])
{
	if (isp_id >= SUPPORTED_ISP_NUM || !dgain)
		return -RTS_ISP_EINVAL;

	dgain[0] = 1.0f;

	return RTS_ISP_OK;
}

static int imx634_get_exposure_gain_info(uint32_t isp_id,
					const struct rts_isp_sensor_exp_gain *exp_gain,
					struct rts_isp_sync_regs *regs)
{
	int i;
	uint16_t total_line;
	uint16_t gain_reg;
	float exp_reg_value_float;
	uint32_t exp_reg_value;
	struct imx634_status *status;
	struct rts_isp_sync_reg *reg;

	if (isp_id >= SUPPORTED_ISP_NUM || !exp_gain || !regs)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];
	gain_reg = get_sensor_gain_reg(exp_gain->analog_gain[0] *
				       exp_gain->digital_gain[0]);
	exp_reg_value_float =
		exp_gain->exposure[0] / status->exp_step + 0.5f;
	exp_reg_value =
		clip_d_word(exp_reg_value_float, 4,
			    (exp_gain->vts - 8));

	if (exp_reg_value == (exp_gain->vts - 8)) {
		total_line = exp_reg_value + 4;
		exp_reg_value = total_line - 8;
	} else {
		total_line = exp_gain->vts;
	}

	reg = regs->reg;

	i = 0;

	//Group Hold
	set_sync_i2c(&reg[i++], 0x0104, 0x01);

	//total length
	set_sync_i2c(&reg[i++], 0x033E, (total_line & 0xff00) >> 8);
	set_sync_i2c(&reg[i++], 0x033F, (total_line & 0xff));

	if (abs(status->last_exposure - exp_gain->exposure[0]) > 0.0001f) {
		//set exposure time
		set_sync_i2c(&reg[i++], 0x022A, (exp_reg_value & 0xff00) >> 8);
		set_sync_i2c(&reg[i++], 0x022B, exp_reg_value & 0xff);

		//set Sensor AGain
		set_sync_i2c(&reg[i++], 0x0205, (gain_reg & 0xff));

		status->last_exposure = exp_gain->exposure[0];
	} else {
		//set Sensor AGain
		set_sync_i2c(&reg[i++], 0x0205, (gain_reg & 0xff));
	}

	//Release Group Hold
	set_sync_i2c(&reg[i++], 0x0104, 0x00);

	regs->num = i;

	return RTS_ISP_OK;
}

static int imx634_check(uint32_t isp_id)
{
	int ret;
	int id;
	struct rts_isp_i2c_reg reg;

	reg.addr = 0x0100;
	reg.data = 0x01;
	ret = rts_isp_write_sensor_reg(isp_id, &reg);
	if (ret)
		return ret;

	reg.addr = 0x0016;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);
	if (ret)
		return ret;
	id = reg.data << 8;

	reg.addr = 0x0017;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);
	if (ret)
		return ret;
	id |= reg.data;

	if (id == 0x0634)
		return RTS_ISP_OK;
	else
		return -RTS_ISP_EINVAL;
}

