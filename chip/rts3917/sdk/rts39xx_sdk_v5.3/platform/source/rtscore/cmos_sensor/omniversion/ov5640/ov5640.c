static int ov5640_get_info(uint32_t isp_id, struct rts_isp_sensor_info *info)
{
	int i;
	struct rts_isp_snr_pwr *up = &info->power_up;
	struct rts_isp_snr_pwr *down = &info->power_down;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
		return -RTS_ISP_EINVAL;

	info->modes.mode[0].hdr = RTS_ISP_HDR_NONE;
	info->modes.mode[0].size.w = 1280;
	info->modes.mode[0].size.h = 720;
	info->modes.mode[0].fps = g_ov5640_fps_info[0].fps;
	info->modes.num = 1;

	info->i2c.i2c_id = 0x3C;
	info->i2c.addr_len = 2;
	info->i2c.data_len = 1;

	i = 0;
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_LOW, 0);
	set_power_item(&up->items[i++], SNR_IO_POWER, PWR_1V8, 10);
	set_power_item(&up->items[i++], SNR_ANALOG_POWER, PWR_2V8, 6000);
	set_power_item(&up->items[i++], SNR_HCLK, CLK_24M, 1000);
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_HIGH, 1000);
	up->num = i;
	i = 0;
	set_power_item(&down->items[i++], SNR_RST_GPIO, 0, 0);
	set_power_item(&down->items[i++], SNR_HCLK, 0, 0);
	set_power_item(&down->items[i++], SNR_ANALOG_POWER, 0, 0);
	set_power_item(&down->items[i++], SNR_IO_POWER, 0, 0);
	down->num = i;

	return RTS_ISP_OK;
}

static const struct fps_info *ov5640_get_fps_info(uint16_t fps)
{
	int i;

	for (i = 0; i < ARRAY_SIZE(g_ov5640_fps_info); i++)
		if (fps == g_ov5640_fps_info[i].fps)
			break;
	if (i == ARRAY_SIZE(g_ov5640_fps_info))
		return NULL;

	return &g_ov5640_fps_info[i];
}

static int ov5640_get_init_info(uint32_t isp_id,
				const struct rts_isp_sensor_mode *mode,
				struct rts_isp_sensor_init_info *info)
{
	const struct fps_info *fps_info;
	struct ov5640_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
		return -RTS_ISP_EINVAL;

	debug("ov5640 get fps %.1f init info\n", mode->fps);

	status = &g_status[isp_id];
	fps_info = ov5640_get_fps_info(mode->fps);
	if (!fps_info)
		return -RTS_ISP_EINVAL;

	set_init_i2c_regs(info->sensor_regs[0], g_ov5640_i2c_init_regs_1, 1000);
	set_init_i2c_regs(info->sensor_regs[1], g_ov5640_i2c_init_regs_2, 1000);
	set_init_i2c_regs(info->sensor_regs[2],
					g_ov5640_i2c_init_regs_3, 200000);
	set_init_i2c_regs(info->sensor_regs[3], g_ov5640_i2c_init_regs_4, 0);
	set_init_i2c_regs(info->sensor_regs[4], g_ov5640_i2c_init_regs_5, 0);

	info->interface.interface = SNR_INTERFACE_MIPI;
	info->interface.mipi.lanes = MIPI_LANE0;
	info->interface.mipi.hs_term = 0x5;
	info->interface.type = YUV_SENSOR;
	info->interface.bit_depth = SNR_8BIT;
	info->interface.type_config.yuv.order.yuv422 = SNR_YUYV;

	info->size.w = 1280;
	info->size.h = 720;
	info->start.x = 0;
	info->start.y = 0;

	info->hts = fps_info->hts;
	info->pclk = fps_info->clk;
	info->min_vts = 740;
	info->max_vts = 65536;

	status->exp_step = 1e6 * info->hts / info->pclk; /* us */
	status->min_vts = info->min_vts;

	return RTS_ISP_OK;
}

static int ov5640_start(uint32_t isp_id)
{
	struct ov5640_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];

	status->last_exposure = 0;

	return RTS_ISP_OK;
}

