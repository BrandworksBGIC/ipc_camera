static int gc05a2_get_info(uint32_t isp_id, struct rts_isp_sensor_info *info)
{
	int i;
	struct rts_isp_snr_pwr *up = &info->power_up;
	struct rts_isp_snr_pwr *down = &info->power_down;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
		return -RTS_ISP_EINVAL;
	info->modes.mode[0].hdr = RTS_ISP_HDR_NONE;
	info->modes.mode[0].size.w = 2592;
	info->modes.mode[0].size.h = 1944;
	info->modes.mode[0].fps = g_gc05a2_fps_info[0].fps;
	info->modes.num = 1;

	info->i2c.i2c_id = 0x37;
	info->i2c.addr_len = 2;
	info->i2c.data_len = 1;

	i = 0;
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_LOW, 0);
	set_power_item(&up->items[i++], SNR_PWDN_GPIO, GPIO_LOW, 0);
	set_power_item(&up->items[i++], SNR_IO_POWER, PWR_1V8, 0);
	set_power_item(&up->items[i++], SNR_CORE_POWER, PWR_1V2, 0);
	set_power_item(&up->items[i++], SNR_ANALOG_POWER, PWR_2V8, 0);
	set_power_item(&up->items[i++], SNR_HCLK, CLK_24M, 1000);
	set_power_item(&up->items[i++], SNR_PWDN_GPIO, GPIO_HIGH, 1000);
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_HIGH, 1000);
	up->num = i;
	i = 0;
	set_power_item(&down->items[i++], SNR_RST_GPIO, 0, 10000);
	set_power_item(&down->items[i++], SNR_PWDN_GPIO, 0, 100000);
	set_power_item(&down->items[i++], SNR_HCLK, 0, 10000);
	set_power_item(&down->items[i++], SNR_ANALOG_POWER, 0, 5000);
	set_power_item(&down->items[i++], SNR_CORE_POWER, 0, 5000);
	set_power_item(&down->items[i++], SNR_IO_POWER, 0, 0);
	down->num = i;

	return RTS_ISP_OK;
}

static const struct fps_info *gc05a2_get_fps_info(uint16_t fps)
{
	int i;

	for (i = 0; i < ARRAY_SIZE(g_gc05a2_fps_info); i++)
		if (fps == g_gc05a2_fps_info[i].fps)
			break;
	if (i == ARRAY_SIZE(g_gc05a2_fps_info))
		return NULL;

	return &g_gc05a2_fps_info[i];
}

static int gc05a2_get_init_info(uint32_t isp_id,
				const struct rts_isp_sensor_mode *mode,
				struct rts_isp_sensor_init_info *info)
{
	const struct fps_info *fps_info;
	struct gc05a2_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
		return -RTS_ISP_EINVAL;

	debug("gc05a2 get fps %.1f init info\n", mode->fps);

	status = &g_status[isp_id];
	fps_info = gc05a2_get_fps_info(mode->fps);
	if (!fps_info)
		return -RTS_ISP_EINVAL;

	debug("fps: %u, pclk: %u, hts: %u\n",
	      fps_info->fps, fps_info->clk, fps_info->hts);

	set_init_i2c_regs(info->sensor_regs[0], g_gc05a2_i2c_init_regs, 0);

	info->interface.interface = SNR_INTERFACE_MIPI;
	info->interface.mipi.lanes = MIPI_LANE0 | MIPI_LANE1;
	info->interface.mipi.hs_term = 0x8;
	info->interface.type = RAW_SENSOR;
	info->interface.bit_depth = SNR_10BIT;

	info->size.w = 2592;
	info->size.h = 1944;
	info->start.x = 0;
	info->start.y = 0;

	info->hts = fps_info->hts;
	info->pclk = fps_info->clk;
	info->min_vts = 2032;
	info->max_vts = 65536;

	status->exp_step = 1e6 * info->hts / info->pclk; /* us */
	status->min_vts = info->min_vts;

	return RTS_ISP_OK;
}

static int gc05a2_start(uint32_t isp_id)
{
	struct gc05a2_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];

	status->last_exposure = 0;

	return RTS_ISP_OK;
}

static uint32_t get_sensor_gain_reg(float fgain)
{
	uint32_t reg_value = 0;

	reg_value = (uint32_t)(fgain * 1024.0f);
	if (reg_value < 0x4000)
		return  reg_value;
	else
		return 0x4000;
}

static float get_sensor_real_gain(uint32_t reg_value)
{
	return reg_value / 1024.0f;
}

static int gc05a2_get_tuned_again(uint32_t isp_id,
				  float again[RTS_ISP_HDR_CHAN_MAX])
{
	int gain_reg;

	if (isp_id >= SUPPORTED_ISP_NUM || !again)
		return -RTS_ISP_EINVAL;

	gain_reg = get_sensor_gain_reg(again[0]);
	again[0] = get_sensor_real_gain(gain_reg);

	return RTS_ISP_OK;
}

static int gc05a2_get_tuned_dgain(uint32_t isp_id,
				  float dgain[RTS_ISP_HDR_CHAN_MAX])
{
	if (isp_id >= SUPPORTED_ISP_NUM || !dgain)
		return -RTS_ISP_EINVAL;

	dgain[0] = 1.0f;

	return RTS_ISP_OK;
}

uint32_t clip_d_word(uint32_t current, uint32_t minimum, uint32_t maximum)
{
	if (current > maximum)
		return maximum;
	if (current < minimum)
		return minimum;
	return current;
}

static int gc05a2_get_exposure_gain_info(uint32_t isp_id,
		 const struct rts_isp_sensor_exp_gain *exp_gain,
		 struct rts_isp_sync_regs *regs)
{
	int i;
	uint32_t gain_reg;
	uint16_t total_line;
	uint32_t exp_reg_value;
	struct gc05a2_status *status;
	struct rts_isp_sync_reg *reg;

	if (isp_id >= SUPPORTED_ISP_NUM || !exp_gain || !regs)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];
	gain_reg = get_sensor_gain_reg(exp_gain->analog_gain[0] *
				       exp_gain->digital_gain[0]);
	reg = regs->reg;

	i = 0;
	if (abs(status->last_exposure - exp_gain->exposure[0]) > 0.001f) {
		uint32_t exposure;

		exposure = exp_gain->exposure[0] / status->exp_step + 0.5f;
		/* vts */
		total_line = exp_gain->vts;
		set_sync_i2c(&reg[i++], 0x0340, total_line >> 8);
		set_sync_i2c(&reg[i++], 0x0341, total_line & 0xff);

		/* exposure */
		exp_reg_value = clip_d_word(exposure, 4, exp_gain->vts - 16);
		set_sync_i2c(&reg[i++], 0x0202, (exp_reg_value >> 8) & 0xff);
		set_sync_i2c(&reg[i++], 0x0203, exp_reg_value & 0xff);

		/* gain */
		set_sync_i2c(&reg[i++], 0x0204, (gain_reg >> 8));
		set_sync_i2c(&reg[i++], 0x0205, (gain_reg & 0xff));


		status->last_exposure = exp_gain->exposure[0];

	} else {
		/* gain */
		set_sync_i2c(&reg[i++], 0x0204, (gain_reg >> 8));
		set_sync_i2c(&reg[i++], 0x0205, (gain_reg & 0xff));

		/* vts */
		total_line = exp_gain->vts;
		set_sync_i2c(&reg[i++], 0x0340, total_line >> 8);
		set_sync_i2c(&reg[i++], 0x0341, total_line & 0xff);
	}

	regs->num = i;

	return RTS_ISP_OK;
}

static int gc05a2_check(uint32_t isp_id)
{
	int ret;
	int id;
	struct rts_isp_i2c_reg reg = {};

	reg.addr = 0x03f0;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);
	if (ret)
		return ret;
	id = reg.data << 8;
	reg.addr = 0x03f1;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);
	if (ret)
		return ret;
	id |= reg.data;
	if (id == 0x05a2)
		return RTS_ISP_OK;
	else
		return -RTS_ISP_EINVAL;
}

