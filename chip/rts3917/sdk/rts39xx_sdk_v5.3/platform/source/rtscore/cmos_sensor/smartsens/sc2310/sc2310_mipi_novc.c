static int sc2310_get_info(uint32_t isp_id, struct rts_isp_sensor_info *info)
{
	int i;
	struct rts_isp_snr_pwr *up = &info->power_up;
	struct rts_isp_snr_pwr *down = &info->power_down;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
		return -RTS_ISP_EINVAL;

	info->modes.mode[0].hdr = RTS_ISP_HDR_LINE_2TO1;
	info->modes.mode[0].size.w = 1920;
	info->modes.mode[0].size.h = 1080;
	info->modes.mode[0].fps = 25;
	info->modes.num = 1;

	info->i2c.i2c_id = 0x30;
	info->i2c.addr_len = 2;
	info->i2c.data_len = 1;

	i = 0;
	set_power_item(&up->items[i++], SNR_HCLK, CLK_24M, 5000);
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_LOW, 0);
	set_power_item(&up->items[i++], SNR_PWDN_GPIO, GPIO_LOW, 0);
	set_power_item(&up->items[i++], SNR_IO_POWER, PWR_1V8, 0);
	set_power_item(&up->items[i++], SNR_CORE_POWER, PWR_1V5, 1000);
	set_power_item(&up->items[i++], SNR_ANALOG_POWER, PWR_2V8, 2000);
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_HIGH, 5000);
	set_power_item(&up->items[i++], SNR_PWDN_GPIO, GPIO_HIGH, 5000);
	up->num = i;
	i = 0;
	set_power_item(&down->items[i++], SNR_RST_GPIO, GPIO_LOW, 0);
	set_power_item(&down->items[i++], SNR_PWDN_GPIO, GPIO_LOW, 0);
	set_power_item(&down->items[i++], SNR_IO_POWER, PWR_NONE, 0);
	set_power_item(&down->items[i++], SNR_CORE_POWER, PWR_NONE, 0);
	set_power_item(&down->items[i++], SNR_ANALOG_POWER, PWR_NONE, 0);
	set_power_item(&down->items[i++], SNR_HCLK, CLK_NONE, 0);
	down->num = i;

	return RTS_ISP_OK;
}

static int sc2310_get_init_info(uint32_t isp_id,
				const struct rts_isp_sensor_mode *mode,
				struct rts_isp_sensor_init_info *info)
{
	struct sc2310_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
		return -RTS_ISP_EINVAL;

	debug("sc2310 get fps %.1f init info\n", mode->fps);
	status = &g_status[isp_id];

	set_init_i2c_regs(info->sensor_regs[0],
		g_sc2310_i2c_init_regs_stagger_dummy_hdr, 0);

	info->interface.interface = SNR_INTERFACE_MIPI;
	info->interface.mipi.hdr = 256;
	info->interface.mipi.lanes = MIPI_LANE0 | MIPI_LANE1;
	info->interface.mipi.hs_term = 0x4;
	info->interface.type = RAW_SENSOR;
	info->interface.bit_depth = SNR_10BIT;
	info->interface.type_config.raw.bayer = SNR_BGGR;

	info->size.w = 1920;
	info->size.h = 1080;
	info->start.x = 0;
	info->start.y = 0;

	info->hts = 1100 * 4;
	info->pclk = 152000000;
	info->min_vts = status->min_vts = 1382;
	info->max_vts = 65535 - info->min_vts;

	status->exp_step = 1e6 * info->hts / 2 / info->pclk; /* us */
	info->exposure_step = 1e6 * info->hts / info->pclk;

	return RTS_ISP_OK;
}

static int sc2310_start(uint32_t isp_id)
{
	struct sc2310_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];

	status->last_exposure = 0;
	rts_isp_set_short_exp_delay(isp_id, 268, 0, 0);

	return RTS_ISP_OK;
}

static int sc2310_get_exposure_range(uint32_t isp_id, uint32_t vts,
				     float ratio[RTS_ISP_HDR_CHAN_MAX - 1],
				     float min_exposure[RTS_ISP_HDR_CHAN_MAX],
				     float max_exposure[RTS_ISP_HDR_CHAN_MAX])
{
	struct sc2310_status *status;
	uint32_t tmp1;
	uint32_t tmp2;

	if (isp_id >= SUPPORTED_ISP_NUM)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];
	tmp1 = 2 * (268 - 4);
	tmp2 = (uint32_t)(2 * (vts - 268 - 5) / (ratio[0] + 1));
	tmp1 = tmp1 < tmp2 ? tmp1 : tmp2;
	max_exposure[1] = tmp1 * status->exp_step;
	min_exposure[1] = 4 * status->exp_step;
	max_exposure[0] = max_exposure[1] * ratio[0];
	min_exposure[0] = min_exposure[1] * ratio[0];

	return RTS_ISP_OK;
}

static uint16_t get_sensor_gain_reg(float fgain)
{
	uint16_t reg_value = 0;
	int i;

	if (fgain >= 21.590)
		reg_value = 0x2f7f;
	else {
		for (i = 0; i < ((ARRAY_SIZE(gain_mapping)) - 1); i++) {
			if ((gain_mapping[i].total_gain <= fgain) &&
			    (fgain < gain_mapping[i + 1].total_gain)) {
				reg_value = gain_mapping[i].ana_gain |
					    gain_mapping[i].fine_gain;
				break;
			}
		}
	}

	return reg_value;
}

static float get_sensor_real_gain(uint16_t reg_value)
{
	float gain = 0.0;
	int i;

	if (reg_value >= 0x2f7f)
		gain = 21.590;
	else {
		for (i = 0; i < ((ARRAY_SIZE(gain_mapping)) - 1); i++) {
			if (reg_value == (gain_mapping[i].ana_gain |
			    gain_mapping[i].fine_gain)) {
				gain = gain_mapping[i].total_gain;
				break;
			}
		}
	}

	return gain;
}

static int sc2310_get_tuned_again(uint32_t isp_id, float *again)
{
	int gain_reg;

	if (isp_id >= SUPPORTED_ISP_NUM || !again)
		return -RTS_ISP_EINVAL;

	gain_reg = get_sensor_gain_reg(again[0]);
	again[0] = get_sensor_real_gain(gain_reg);
	gain_reg = get_sensor_gain_reg(again[1]);
	again[1] = get_sensor_real_gain(gain_reg);

	return RTS_ISP_OK;
}

static int sc2310_get_tuned_dgain(uint32_t isp_id,
				  float dgain[RTS_ISP_HDR_CHAN_MAX])
{
	if (isp_id >= SUPPORTED_ISP_NUM || !dgain)
		return -RTS_ISP_EINVAL;

	dgain[0] = 1.0f;
	dgain[1] = 1.0f;

	return RTS_ISP_OK;
}

static int sc2310_get_exposure_gain_info(uint32_t isp_id,
				const struct rts_isp_sensor_exp_gain *exp_gain,
				struct rts_isp_sync_regs *regs)
{
	int i;
	struct sc2310_status *status;
	struct rts_isp_sync_reg *reg;
	uint16_t exp_cnt[2];
	uint16_t gain_reg[2];

	if (isp_id >= SUPPORTED_ISP_NUM || !exp_gain || !regs)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];

	for (i = 0; i < 2; i++) {
		exp_cnt[i] = (2.0 * exp_gain->exposure[i] /
					status->exp_step + 0.5f);
		gain_reg[i] =
			get_sensor_gain_reg(exp_gain->analog_gain[i] *
						exp_gain->digital_gain[i]);
	}

	reg = regs->reg;
	i = 0;
	/* set vts */
	set_sync_i2c(&reg[i++], 0x320e, (2 * exp_gain->vts) >> 8);
	set_sync_i2c(&reg[i++], 0x320f, (2 * exp_gain->vts) & 0xff);
	/* set exposure */
	set_sync_i2c(&reg[i++], 0x3e01, (exp_cnt[0] << 4) >> 8);
	set_sync_i2c(&reg[i++], 0x3e02, (exp_cnt[0] << 4) & 0xff);
	set_sync_i2c(&reg[i++], 0x3e04, (exp_cnt[1] << 4) >> 8);
	set_sync_i2c(&reg[i++], 0x3e05, (exp_cnt[1] << 4) & 0xff);
	/* set gain */
	set_sync_i2c(&reg[i++], 0x3e08, (gain_reg[0] >> 8));
	set_sync_i2c(&reg[i++], 0x3e09, (gain_reg[0] & 0xff));
	set_sync_i2c(&reg[i++], 0x3e12, (gain_reg[1] >> 8));
	set_sync_i2c(&reg[i++], 0x3e13, (gain_reg[1] & 0xff));

	set_sync_i2c(&reg[i++], 0x3812, 0x00);
	if (exp_cnt[0] < 5 * 16)
		set_sync_i2c(&reg[i++], 0x3314, 0x14);
	else if (exp_cnt[0] > 10 * 16)
		set_sync_i2c(&reg[i++], 0x3314, 0x04);
	set_sync_i2c(&reg[i++], 0x3812, 0x30);

	regs->num = i;

	return RTS_ISP_OK;
}

static int sc2310_check(uint32_t isp_id)
{
	int ret;
	int id;
	struct rts_isp_i2c_reg reg = {};

	reg.addr = 0x3107;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);
	if (ret)
		return ret;
	id = reg.data << 8;

	reg.addr = 0x3108;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);
	if (ret)
		return ret;
	id |= reg.data;

	if (id == 0x2311)
		return RTS_ISP_OK;
	else
		return -RTS_ISP_EINVAL;
}

