static int sc5336p_get_info(uint32_t isp_id, struct rts_isp_sensor_info *info)
{
	int i;
	struct rts_isp_snr_pwr *up = &info->power_up;
	struct rts_isp_snr_pwr *down = &info->power_down;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
		return -RTS_ISP_EINVAL;

	i = 0;
	info->modes.mode[i].hdr = RTS_ISP_HDR_NONE;
	info->modes.mode[i].size.w = 2816;
	info->modes.mode[i].size.h = 1584;
	info->modes.mode[i].fps = 30;
	i++;
	info->modes.mode[i].hdr = RTS_ISP_HDR_LINE_2TO1;
	info->modes.mode[i].size.w = 2816;
	info->modes.mode[i].size.h = 1584;
	info->modes.mode[i].fps = 15;
	i++;
	info->modes.num = i;

	info->i2c.i2c_id = 0x30;
	info->i2c.addr_len = 2;
	info->i2c.data_len = 1;

	i = 0;
	set_power_item(&up->items[i++], SNR_PWDN_GPIO, GPIO_LOW, 0);
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_LOW, 0);
	set_power_item(&up->items[i++], SNR_IO_POWER, PWR_1V8, 1000);
	set_power_item(&up->items[i++], SNR_CORE_POWER, PWR_1V5, 1000);
	set_power_item(&up->items[i++], SNR_ANALOG_POWER, PWR_2V8, 5000);
	set_power_item(&up->items[i++], SNR_HCLK, CLK_27M, 5000);
	up->num = i;
	i = 0;
	set_power_item(&down->items[i++], SNR_RST_GPIO, 0, 0);
	set_power_item(&down->items[i++], SNR_HCLK, 0, 0);
	set_power_item(&down->items[i++], SNR_IO_POWER, 0, 0);
	set_power_item(&down->items[i++], SNR_CORE_POWER, 0, 0);
	set_power_item(&down->items[i++], SNR_ANALOG_POWER, 0, 0);
	down->num = i;

	return RTS_ISP_OK;
}

static int sc5336p_get_init_info(uint32_t isp_id,
				const struct rts_isp_sensor_mode *mode,
				struct rts_isp_sensor_init_info *info)
{
	struct sc5336p_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
		return -RTS_ISP_EINVAL;

	debug("sc5336p get fps %.1f init info\n", mode->fps);

	status = &g_status[isp_id];
	status->hdr = mode->hdr;
	/* HDR MODE */
	if (mode->hdr == RTS_ISP_HDR_LINE_2TO1) {
		set_init_i2c_regs(info->sensor_regs[0],
				g_sc5336p_i2c_init_regs_vc_hdr, 0);

		info->interface.interface = SNR_INTERFACE_MIPI;
		info->interface.mipi.hdr = MIPI_HDR_VC;
		info->interface.mipi.lanes = MIPI_LANE0 | MIPI_LANE1;
		info->interface.mipi.hs_term = 0x7;
		info->interface.type = RAW_SENSOR;
		info->interface.bit_depth = SNR_10BIT;
		info->interface.type_config.raw.bayer = SNR_BGGR;

		info->size.w = 2816;
		info->size.h = 1584;
		info->start.x = 0;
		info->start.y = 0;

		info->hts = 3200;
		info->pclk = 158400000;
		info->min_vts = status->min_vts = 3300;
		info->max_vts = 65535 - info->min_vts;

		status->exp_step = 1e6 * info->hts / info->pclk; /* us */
		info->exposure_step = status->exp_step;
	/* LINEAR MODE */
	} else {
		set_init_i2c_regs(info->sensor_regs[0],
				  g_sc5336p_i2c_init_regs_linear, 0);

		info->interface.interface = SNR_INTERFACE_MIPI;
		info->interface.mipi.hdr = MIPI_HDR_NONE;
		info->interface.mipi.lanes = MIPI_LANE0 | MIPI_LANE1;
		info->interface.mipi.hs_term = 0x7;
		info->interface.type = RAW_SENSOR;
		info->interface.bit_depth = SNR_10BIT;
		info->interface.type_config.raw.bayer = SNR_BGGR;

		info->size.w = 2816;
		info->size.h = 1584;
		info->start.x = 0;
		info->start.y = 0;

		info->hts = 3200;
		info->pclk = 158400000;
		info->min_vts = status->min_vts = 1650;
		info->max_vts = 65535 - info->min_vts;

		status->exp_step = 1e6 * info->hts / info->pclk; /* us */
	}

	return RTS_ISP_OK;
}

static int sc5336p_start(uint32_t isp_id)
{
	struct sc5336p_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];

	status->last_exposure = 0;

	return RTS_ISP_OK;
}

static int sc5336p_get_exposure_range(uint32_t isp_id, uint32_t vts,
				     float ratio[RTS_ISP_HDR_CHAN_MAX - 1],
				     float min_exposure[RTS_ISP_HDR_CHAN_MAX],
				     float max_exposure[RTS_ISP_HDR_CHAN_MAX])
{
	struct sc5336p_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];

	if (status->hdr == RTS_ISP_HDR_NONE) {
	/* LINEAR MODE */
		min_exposure[0] = 2 * status->exp_step;
		max_exposure[0] = (vts - 8) * status->exp_step;
	} else {
	/* HDR MODE */
		uint32_t tmp1;
		uint32_t tmp2;

		tmp1 = MAX_SHORT_EXP - 9;
		tmp2 = (vts - MAX_SHORT_EXP - 11) / ratio[0];
		tmp1 = tmp1 < tmp2 ? tmp1 : tmp2;
		max_exposure[1] = tmp1 * (status->exp_step / 2);
		min_exposure[1] = 2 * (status->exp_step / 2);
		max_exposure[0] = max_exposure[1] * ratio[0];
		min_exposure[0] = min_exposure[1] * ratio[0];
	}

	return RTS_ISP_OK;
}

static uint16_t get_sensor_gain_reg(float fgain)
{
	uint16_t reg_value = 0x00;

	if (fgain >= 32.00f)
		reg_value = 0x1f;
	else if (fgain >= 16.00f)
		reg_value = 0x0f;
	else if (fgain >= 8.00f)
		reg_value = 0x0b;
	else if (fgain >= 4.00f)
		reg_value = 0x09;
	else if (fgain >= 2.00f)
		reg_value = 0x08;
	else if (fgain >= 1.00f)
		reg_value = 0x00;

	return reg_value;
}

static float get_sensor_real_gain(uint16_t reg_value)
{
	float gain = 1.0;

	if (reg_value >= 0x1f)
		gain = 32.00;
	else if (reg_value >= 0x0f)
		gain = 16;
	else if (reg_value >= 0x0b)
		gain = 8.00;
	else if (reg_value >= 0x09)
		gain = 4.00;
	else if (reg_value >= 0x08)
		gain = 2.00;
	else
		gain = 1.00;

	return gain;
}

static uint32_t clip_d_word(uint32_t current, uint32_t minimum,
			    uint32_t maximum)
{
	if (current > maximum)
		return maximum;
	if (current < minimum)
		return minimum;
	return current;
}

static int sc5336p_get_tuned_again(uint32_t isp_id, float *again)
{
	int gain_reg;

	if (isp_id >= SUPPORTED_ISP_NUM || !again)
		return -RTS_ISP_EINVAL;

	gain_reg = get_sensor_gain_reg(again[0]);
	again[0] = get_sensor_real_gain(gain_reg);
	gain_reg = get_sensor_gain_reg(again[1]);
	again[1] = get_sensor_real_gain(gain_reg);

	return RTS_ISP_OK;
}

static int sc5336p_get_tuned_dgain(uint32_t isp_id,
				  float dgain[RTS_ISP_HDR_CHAN_MAX])
{
	if (isp_id >= SUPPORTED_ISP_NUM || !dgain)
		return -RTS_ISP_EINVAL;

	dgain[0] = 1.0f;
	dgain[1] = 1.0f;

	return RTS_ISP_OK;
}

static int sc5336p_get_exposure_gain_info(uint32_t isp_id,
			const struct rts_isp_sensor_exp_gain *exp_gain,
			struct rts_isp_sync_regs *regs)
{

	int i;
	struct sc5336p_status *status;
	struct rts_isp_sync_reg *reg;

	if (isp_id >= SUPPORTED_ISP_NUM || !exp_gain || !regs)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];

	if (status->hdr == RTS_ISP_HDR_NONE) {
	/* LINEAR MODE */
		int exp_set;
		uint16_t total_line;
		uint16_t gain_reg;
		float exp_reg_value_float;
		uint32_t exp_reg_value;
		float gain;

		gain = exp_gain->analog_gain[0] * exp_gain->digital_gain[0];
		gain_reg = get_sensor_gain_reg(gain);

		total_line = exp_gain->vts;

		exp_reg_value_float =
			1.0 * exp_gain->exposure[0] / status->exp_step + 0.5f;
		exp_reg_value =
			clip_d_word(exp_reg_value_float, 2,
			      (1 * total_line - 8));
		exp_reg_value = exp_reg_value << 4;

		total_line = (total_line + 1) / 2 * 2;
		reg = regs->reg;

		i = 0;
		/* set vts */
		set_sync_i2c(&reg[i++], 0x320e, (total_line >> 8));
		set_sync_i2c(&reg[i++], 0x320f, (total_line & 0xff));
		exp_set = abs(status->last_exposure -
			      exp_gain->exposure[0]) > 0.001f;
		/* set exposure */
		if (exp_set) {
			set_sync_i2c(&reg[i++], 0x3e00, exp_reg_value >> 16);
			set_sync_i2c(&reg[i++], 0x3e01,
				     (exp_reg_value & 0xff00) >> 8);
			set_sync_i2c(&reg[i++], 0x3e02, exp_reg_value & 0xff);
			status->last_exposure = exp_gain->exposure[0];
		}
		/* set gain */
		set_sync_i2c(&reg[i++], 0x3e09, (gain_reg & 0xff));

		regs->num = i;
	} else {
	/* HDR MODE */
		uint16_t exp_cnt[2];
		uint16_t gain_reg[2];

		for (i = 0; i < 2; i++) {
			exp_cnt[i] = (exp_gain->exposure[i] /
					      (status->exp_step / 2) +
				      0.5f);
			gain_reg[i] =
				get_sensor_gain_reg(exp_gain->analog_gain[i] *
						    exp_gain->digital_gain[i]);
		}

		reg = regs->reg;
		i = 0;
		/* set vts */
		set_sync_i2c(&reg[i++], 0x320e, (exp_gain->vts) >> 8);
		set_sync_i2c(&reg[i++], 0x320f, (exp_gain->vts) & 0xff);
		/* set exposure */
		set_sync_i2c(&reg[i++], 0x3e00, (exp_cnt[0] >> 12));
		set_sync_i2c(&reg[i++], 0x3e01, (exp_cnt[0] << 4) >> 8);
		set_sync_i2c(&reg[i++], 0x3e02, (exp_cnt[0] << 4) & 0xff);
		set_sync_i2c(&reg[i++], 0x3e22, (exp_cnt[1] >> 12));
		set_sync_i2c(&reg[i++], 0x3e04, (exp_cnt[1] << 4) >> 8);
		set_sync_i2c(&reg[i++], 0x3e05, (exp_cnt[1] << 4) & 0xff);
		/* set gain */
		set_sync_i2c(&reg[i++], 0x3e09, (gain_reg[0] & 0xff));
		set_sync_i2c(&reg[i++], 0x3e13, (gain_reg[1] & 0xff));

		regs->num = i;
	}

	return RTS_ISP_OK;
}

static int sc5336p_check(uint32_t isp_id)
{
	int ret;
	int id;
	struct rts_isp_i2c_reg reg = {};

	reg.addr = 0x3107;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);
	if (ret)
		return ret;
	id = reg.data << 8;

	reg.addr = 0x3108;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);
	if (ret)
		return ret;
	id |= reg.data;

	if (id == 0xce50)
		return RTS_ISP_OK;
	else
		return -RTS_ISP_EINVAL;
}

