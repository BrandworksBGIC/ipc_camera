#define RTS_SEL_I2S_FORMAT		(12)
#define RTS_INV_TDM_LRCK_MST		(15)
#define RTS_INV_TDM_LRCK		(16)
#define RTS_INV_TDM_BCLK_MST		(17)
#define RTS_INV_TDM_BCLK		(18)
#define RTS_SEL_I2S_DATA_LEN		(19)

/* RTS_REG_I2S_OCP_CTL */
#define RTS_LDOI2S_POW			(0)

/* RTS_REG_I2S_OCP_CFG */
#define RTS_REG_TUNE_VO		(0)

/*RTS_REG_SPDIF_CFG*/
