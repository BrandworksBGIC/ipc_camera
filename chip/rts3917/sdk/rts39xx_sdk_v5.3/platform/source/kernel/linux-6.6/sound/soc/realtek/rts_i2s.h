#define RTS_BIT_SPDIF_ZEROB_DATA				(1)
#define RTS_BIT_SPDIF_OUT_AUDIO_TYPE			(2)
#define RTS_BIT_SPDIF_OUT_COPY				(3)
#define RTS_BIT_SPDIF_OUT_EN					(4)
#define RTS_BIT_SPDIF_OUT_PRE					(5)
#define RTS_BIT_SPDIF_OUT_PRO					(6)
#define RTS_BIT_SPDIF_OUT_VALID				(7)
#define RTS_BIT_SPDIF_OUT_VCFG				(8)
#define RTS_BIT_SPDIF_OUT_LEVEL				(9)
#define RTS_BIT_SPDIF_BITS						(10)
#define RTS_BIT_SPDIF_SR						(13)
#define RTS_BIT_SPDIF_OUT_CC					(16)

