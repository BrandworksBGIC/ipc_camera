#define RTS_I2S_CODEC_CE_512FS		2

/* i2s reg */
#define RTS_REG_I2S_CTL			0x0
#define RTS_REG_I2S_CFG			0x4

/* i2s power reg */
#define RTS_REG_I2S_OCP_CTL		0x8
#define RTS_REG_I2S_OCP_CFG		0xc

/* spdif cfg reg */
#define RTS_REG_SPDIF_CFG		0x100

/* RTS_REG_I2S_CTL */
#define RTS_I2S_IN_GO			(0)
#define RTS_I2S_OUT_GO			(1)
#define RTS_EN_I2S_MONO			(2)
#define RTS_I2S_LJ_MODE_SEL		(3)
#define RTS_I2S_LJ_MONO_MODE_SEL	(4)
#define RTS_TDM_SELF_LPBK_EN		(5)
#define RTS_I2S_SCK_OE			(6)
#define RTS_I2S_WS_OE			(7)
#define RTS_SCK_GEN_SEL			(15)
#define RTS_BCLK_INT_DIV		(16)
#define RTS_MCLK_DIV_SEL		(24)
#define RTS_I2S_SAMPLE_RATE		(28)

/* RTS_REG_I2S_CFG */
#define RTS_TDM_RW_PULSE_WD_SEL		(0)
